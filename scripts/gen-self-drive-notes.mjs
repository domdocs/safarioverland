/**
 * Regenerate lib/field-notes/self-drive-notes.ts (and the static-param
 * list app/field-notes/self-drive/[slug]/slugs.json) from the markdown
 * guides in handoff/relaunch/copy/field-notes/.
 *
 * The guides are baked into a TS module so the pages never read the
 * filesystem at request time (see CHANGELOG 2026-08-07: `app/` and
 * `handoff/` exist during a build but not inside the deployed function).
 *
 * Run after editing any guide, then regenerate the dates map so the
 * sitemap picks up new slugs:
 *
 *   node scripts/gen-self-drive-notes.mjs
 *   node scripts/gen-field-note-dates.mjs
 *
 * SOURCES.md is research material, not a guide, and is skipped.
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"

const SRC = path.join(process.cwd(), "handoff", "relaunch", "copy", "field-notes")
const OUT = path.join(process.cwd(), "lib", "field-notes", "self-drive-notes.ts")
const SLUGS_OUT = path.join(
  process.cwd(),
  "app",
  "field-notes",
  "self-drive",
  "[slug]",
  "slugs.json",
)

/** Reading order on the index and in "read next" rails. Guides not
 *  listed here are appended alphabetically. */
const ORDER = [
  "namibia-or-zimbabwe-first",
  "choosing-a-vehicle",
  "driving-on-the-left",
  "gravel-roads",
  "border-crossings",
  "fuel-cash-and-signal",
  "after-dark-and-wildlife-on-the-road",
]

const REQUIRED = ["slug", "title", "description", "eyebrow"]

function parse(file) {
  const raw = readFileSync(path.join(SRC, file), "utf8").replace(/\r\n/g, "\n")
  const m = raw.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/)
  if (!m) throw new Error(`${file}: missing frontmatter`)
  const fm = {}
  for (const line of m[1].split("\n")) {
    const kv = line.match(/^([A-Za-z_][\w-]*):\s*(.*)$/)
    if (!kv) continue
    let value = kv[2].trim()
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1)
    }
    fm[kv[1]] = value
  }
  for (const key of REQUIRED) {
    if (!fm[key]) throw new Error(`${file}: frontmatter is missing "${key}"`)
  }
  return {
    slug: fm.slug,
    title: fm.title,
    description: fm.description,
    eyebrow: fm.eyebrow,
    body: m[2].trim() + "\n",
  }
}

const notes = readdirSync(SRC)
  .filter((f) => f.endsWith(".md") && f !== "SOURCES.md")
  .map(parse)
  .sort((a, b) => {
    const ia = ORDER.indexOf(a.slug)
    const ib = ORDER.indexOf(b.slug)
    if (ia !== -1 || ib !== -1) {
      return (ia === -1 ? Infinity : ia) - (ib === -1 ? Infinity : ib)
    }
    return a.slug.localeCompare(b.slug)
  })

const out = `/**
 * Self-drive Field Notes, baked from handoff/relaunch/copy/field-notes/*.md.
 *
 * GENERATED by scripts/gen-self-drive-notes.mjs — do not edit by hand.
 * Edit the markdown, then run:
 *   node scripts/gen-self-drive-notes.mjs
 *   node scripts/gen-field-note-dates.mjs
 *
 * Rendered at /field-notes/self-drive/<slug>. A static module rather
 * than a filesystem read so it works inside the deployed function.
 */

export type SelfDriveNote = {
  slug: string
  title: string
  description: string
  /** e.g. "Self-drive · 6 min" */
  eyebrow: string
  /** Markdown body, frontmatter stripped. */
  body: string
}

export const SELF_DRIVE_NOTES: SelfDriveNote[] = ${JSON.stringify(notes, null, 2)}

export function getSelfDriveNote(slug: string): SelfDriveNote | undefined {
  return SELF_DRIVE_NOTES.find((n) => n.slug === slug)
}
`

writeFileSync(OUT, out)
writeFileSync(SLUGS_OUT, JSON.stringify(notes.map((n) => n.slug), null, 2) + "\n")
console.log(`Wrote ${notes.length} guides to ${OUT} and ${SLUGS_OUT}`)
